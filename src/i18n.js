let locale = 'zh-CN';
export function normalizeLocale(value) { return value === 'en' ? 'en' : 'zh-CN'; }
export function localeFromURL(href = 'http://localhost/') {
  try { return normalizeLocale(new URL(href).searchParams.get('lang')); } catch { return 'zh-CN'; }
}
export function getLocale() { return locale; }
export function setLocale(value) { locale = normalizeLocale(value); return locale; }
export function t(key, values = {}) {
  const message = locale === 'en' ? (english[key] ?? key) : key;
  return message.replace(/\{(\w+)\}/g, (placeholder, name) => Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}
export function translateUI(root) {
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.getAttribute('data-i18n'));
  for (const attribute of ['title', 'aria-label', 'placeholder', 'content']) {
    for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) {
      element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
    }
  }
}
